// Writes src/environments/environment.prod.ts from the API_URL env var at build time
// (Vercel / Netlify). Example: API_URL=https://exorcity-api.onrender.com/api
import { writeFileSync } from 'node:fs';

const apiUrl = (process.env.API_URL || '/api').replace(/\/$/, '');
const content = `// Generated by scripts/set-env.mjs, do not edit by hand.
export const environment = {
  production: true,
  apiUrl: ${JSON.stringify(apiUrl)},
};
`;
writeFileSync(new URL('../src/environments/environment.prod.ts', import.meta.url), content);
console.log(`environment.prod.ts -> apiUrl=${apiUrl}`);
